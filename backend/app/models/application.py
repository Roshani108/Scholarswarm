from typing import List, Optional
from pydantic import BaseModel, Field

class FactCheckClaim(BaseModel):
    sentence_or_claim: str
    student_evidence: str
    source_ref: str # e.g. "GitHub: multi-agent-rag repo", "Resume: Jalandhar CSE 8.2 CGPA"
    is_verified: bool = True

class SOPDraft(BaseModel):
    opportunity_id: str
    opportunity_title: str
    target_institution: str
    statement_of_purpose: str
    letter_of_recommendation_template: str
    required_documents: List[str] = Field(default_factory=list)
    fact_checks: List[FactCheckClaim] = Field(default_factory=list)
    word_count: int = 0
    generated_at: str
    disclaimer: str = "DRAFT ONLY. Generated by ScholarSwarm AI for research and drafting assistance. Do not submit directly without manual verification and personalization."
